SELECT
    RIND,
    DENUMIRE,
    '[' || RIND || ']' AS RIND_CHECK,
    '[' || DENUMIRE || ']' AS DENUMIRE_CHECK
FROM CIS2.MD_RIND
WHERE FORM = 49
  AND CAPITOL = 1049
  AND CAPITOL_VERS = 2015
  AND STATUT = '1'
 -- AND RIND LIKE '4%'
  AND LENGTH(RIND) > 3
  AND (
        RIND <> TRIM(RIND)
        OR DENUMIRE <> TRIM(DENUMIRE)
      )
ORDER BY ORDINE;


